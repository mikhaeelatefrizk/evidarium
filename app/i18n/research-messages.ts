// Only application-owned messages pass through here; research text stays verbatim.
export function researchMessage(value:string|undefined|null,t:Translate):string{
 const message=value||'';
 let match=message.match(/^RIS (.+) is not mapped; keep your original export\.$/);
 if(match)return t('RIS {field} is not mapped; keep your original export.',{field:match[1]});
 match=message.match(/^RIS type (.+) is exported as a generic article\.$/);
 if(match)return t('RIS type {type} is exported as a generic article.',{type:match[1]});
 match=message.match(/^Unknown source citation: ([\s\S]+)$/);
 if(match)return t('Unknown source citation: {citation}',{citation:match[1]});
 match=message.match(/^Cites an excluded record: ([\s\S]+)$/);
 if(match)return t('Cites an excluded record: {title}',{title:match[1]});
 match=message.match(/^Waiting for live cited response (\d+)$/);
 if(match)return t('Waiting for live cited response {number}',{number:match[1]});
 match=message.match(/^live cited conversation (\d+)$/);
 if(match)return t('live cited conversation {number}',{number:match[1]});
 match=message.match(/^(.+) passed$/);
 if(match)return t('{check} passed',{check:researchMessage(match[1],t)});
 match=message.match(/^(?:page|Page)[: ](\d+)$/);
 if(match)return t('Page {number}',{number:match[1]});
 match=message.match(/^(?:sheet|Sheet)[: ](.+)$/);
 if(match)return t('Sheet {name}',{name:match[1]});
 match=message.match(/^Only the first 50 of (\d+) pages were read\.$/);
 if(match)return t('Only the first 50 of {count} pages were read.',{count:match[1]});
 match=message.match(/^Page (\d+) has no extracted text; scanned text, figures or unavailable character maps may require another method\.$/);
 if(match)return t('Page {number} has no extracted text; scanned text, figures or unavailable character maps may require another method.',{number:match[1]});
 match=message.match(/^PDF\.js (.+) via unpdf 1\.8\.1$/);
 if(match)return t('PDF.js {version} via unpdf 1.8.1',{version:match[1]});
 match=message.match(/^Record (\d+) (is not a bibliographic object|has no title\. Nothing was imported)\.$/);
 if(match)return t('Record {number} '+match[2]+'.',{number:match[1]});
 match=message.match(/^Invalid RIS line (\d+); use a standard RIS export\.$/);
 if(match)return t('Invalid RIS line {number}; use a standard RIS export.',{number:match[1]});
 match=message.match(/^(Title|Draft) must be text of at most ([\d,]+) characters\.$/);
 if(match)return t(match[1]+' must be text of at most {count} characters.',{count:match[2]});
 return t(message);
}
